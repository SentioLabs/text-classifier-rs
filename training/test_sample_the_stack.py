class TestSampleLanguage:
    def _make_mock_dataset(self, items):
        """Create a mock streaming dataset that yields items."""
        mock_ds = MagicMock()
        mock_ds.shuffle.return_value = iter(items)
        return mock_ds

    def test_returns_list_of_dicts(self):
        from sample_the_stack import sample_language

        items = [
            {"content": "\n".join(f"line {i}" for i in range(20))}
            for _ in range(5)
        ]
        with patch("sample_the_stack.datasets") as mock_datasets:
            mock_ds = self._make_mock_dataset(items)
            mock_datasets.load_dataset.return_value = mock_ds
            results = sample_language("python", "code", "python", count=3, seed=42)

        assert isinstance(results, list)
        assert len(results) == 3

    def test_provenance_fields_present(self):
        from sample_the_stack import sample_language

        items = [
            {"content": "\n".join(f"line {i}" for i in range(20))}
            for _ in range(5)
        ]
        with patch("sample_the_stack.datasets") as mock_datasets:
            mock_ds = self._make_mock_dataset(items)
            mock_datasets.load_dataset.return_value = mock_ds
            results = sample_language("python", "code", "python", count=1, seed=42)

        sample = results[0]
        required_fields = [
            "text", "expected_category", "sub_type", "boundary_pair",
            "model", "temperature", "prompt_template", "content_domain",
            "length_bucket", "reasoning_mode",
        ]
        for field in required_fields:
            assert field in sample, f"Missing provenance field: {field}"

    def test_provenance_field_values(self):
        from sample_the_stack import sample_language

        items = [
            {"content": "\n".join(f"line {i}" for i in range(20))}
            for _ in range(5)
        ]
        with patch("sample_the_stack.datasets") as mock_datasets:
            mock_ds = self._make_mock_dataset(items)
            mock_datasets.load_dataset.return_value = mock_ds
            results = sample_language("python", "code", "python", count=1, seed=42)

        sample = results[0]
        assert sample["expected_category"] == "code"
        assert sample["sub_type"] == "python"
        assert sample["boundary_pair"] is None
        assert sample["model"] == "real/the-stack-v1"
        assert sample["temperature"] is None
        assert sample["prompt_template"] is None
        assert sample["content_domain"] == "python"
        assert sample["length_bucket"] in ("short", "medium", "long")
        assert sample["reasoning_mode"] is False

    def test_filters_out_bad_samples(self):
        from sample_the_stack import sample_language

        # Mix of good and bad items
        good_content = "\n".join(f"line {i}" for i in range(20))
        bad_content = "too\nshort"  # < 5 non-empty lines
        items = [
            {"content": bad_content},
            {"content": bad_content},
            {"content": good_content},
            {"content": good_content},
        ]
        with patch("sample_the_stack.datasets") as mock_datasets:
            mock_ds = self._make_mock_dataset(items)
            mock_datasets.load_dataset.return_value = mock_ds
            results = sample_language("python", "code", "python", count=2, seed=42)

        assert len(results) == 2

    def test_calls_load_dataset_correctly(self):
        from sample_the_stack import sample_language

        items = [
            {"content": "\n".join(f"line {i}" for i in range(20))}
            for _ in range(3)
        ]
        with patch("sample_the_stack.datasets") as mock_datasets:
            mock_ds = self._make_mock_dataset(items)
            mock_datasets.load_dataset.return_value = mock_ds
            sample_language("python", "code", "python", count=1, seed=42)

        mock_datasets.load_dataset.assert_called_once_with(
            "bigcode/the-stack",
            data_dir="data/python",
            streaming=True,
            split="train",
        )


