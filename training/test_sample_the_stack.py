class TestFilterSample:
    def test_rejects_too_few_lines(self):
        from sample_the_stack import filter_sample

        content = "line1\nline2\nline3\nline4\n"
        assert filter_sample(content) is False

    def test_rejects_too_many_lines(self):
        from sample_the_stack import filter_sample

        content = "\n".join(f"line {i}" for i in range(501))
        assert filter_sample(content) is False

    def test_rejects_auto_generated_code_generated(self):
        from sample_the_stack import filter_sample

        content = "// Code generated by protoc-gen-go. DO NOT EDIT.\n" + "\n".join(
            f"func f{i}() {{}}" for i in range(10)
        )
        assert filter_sample(content) is False

    def test_rejects_auto_generated_hash_auto(self):
        from sample_the_stack import filter_sample

        content = "# AUTO-GENERATED FILE\n" + "\n".join(
            f"item_{i} = {i}" for i in range(10)
        )
        assert filter_sample(content) is False

    def test_rejects_auto_generated_c_style(self):
        from sample_the_stack import filter_sample

        content = "/* AUTO GENERATED */\n" + "\n".join(
            f"int x{i} = {i};" for i in range(10)
        )
        assert filter_sample(content) is False

    def test_rejects_auto_generated_this_file_is(self):
        from sample_the_stack import filter_sample

        content = "# This file is auto-generated\n" + "\n".join(
            f"val_{i} = {i}" for i in range(10)
        )
        assert filter_sample(content) is False

    def test_rejects_auto_generated_do_not_edit(self):
        from sample_the_stack import filter_sample

        content = "// DO NOT EDIT\n" + "\n".join(
            f"const x{i} = {i};" for i in range(10)
        )
        assert filter_sample(content) is False

    def test_rejects_binary_content(self):
        from sample_the_stack import filter_sample

        # 15% non-printable characters
        printable = "a" * 85 + "\n" * 10
        non_printable = "\x00" * 15
        content = printable + non_printable
        # Ensure at least 5 non-empty lines
        content = "\n".join(["normal line"] * 10) + "\n" + "\x00" * 20
        assert filter_sample(content) is False

    def test_accepts_valid_code(self):
        from sample_the_stack import filter_sample

        content = "\n".join([
            "def hello():",
            '    print("Hello, world!")',
            "",
            "def goodbye():",
            '    print("Goodbye!")',
            "",
            "if __name__ == '__main__':",
            "    hello()",
            "    goodbye()",
            "",
        ])
        assert filter_sample(content) is True

    def test_accepts_exactly_5_non_empty_lines(self):
        from sample_the_stack import filter_sample

        content = "\n".join([
            "line 1",
            "line 2",
            "line 3",
            "line 4",
            "line 5",
        ])
        assert filter_sample(content) is True

    def test_accepts_exactly_500_lines(self):
        from sample_the_stack import filter_sample

        content = "\n".join(f"line {i}" for i in range(500))
        assert filter_sample(content) is True


