            mock_ds.shuffle.return_value = iter(items)
            mock_datasets.load_dataset.return_value = mock_ds

            with tempfile.TemporaryDirectory() as tmpdir:
                output = os.path.join(tmpdir, "test.jsonl")
                sample_all(
                    output_path=output,
                    per_language=2,
                    seed=42,
                    languages=["python"],
                )
                assert os.path.exists(output)
                with open(output) as f:
                    lines = [line.strip() for line in f if line.strip()]
                assert len(lines) == 2
                sample = json.loads(lines[0])
                assert sample["expected_category"] == "code"
                assert sample["sub_type"] == "python"
