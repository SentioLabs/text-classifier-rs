class TestSampleAll:
    def test_writes_jsonl_output(self):
        from sample_the_stack import sample_all

        good_content = "\n".join(f"line {i}" for i in range(20))

        with patch("sample_the_stack.datasets") as mock_datasets:
            mock_ds = MagicMock()
