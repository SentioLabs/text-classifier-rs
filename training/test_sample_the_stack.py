class TestDryRun:
    def test_dry_run_prints_plan_no_output_file(self, capsys):
        from sample_the_stack import main

        with tempfile.TemporaryDirectory() as tmpdir:
            output = os.path.join(tmpdir, "test.jsonl")
            main(["--output", output, "--dry-run"])
            captured = capsys.readouterr()
            assert "DRY RUN" in captured.out
            assert not os.path.exists(output)

    def test_dry_run_shows_language_plan(self, capsys):
        from sample_the_stack import main

        with tempfile.TemporaryDirectory() as tmpdir:
            output = os.path.join(tmpdir, "test.jsonl")
            main(["--output", output, "--dry-run"])
            captured = capsys.readouterr()
            assert "python" in captured.out.lower()
            assert "14" in captured.out or "languages" in captured.out.lower()

    def test_dry_run_with_language_filter(self, capsys):
        from sample_the_stack import main

        with tempfile.TemporaryDirectory() as tmpdir:
            output = os.path.join(tmpdir, "test.jsonl")
            main(["--output", output, "--dry-run", "--languages", "python,rust"])
            captured = capsys.readouterr()
            assert "python" in captured.out.lower()
            assert "rust" in captured.out.lower()
            # Should show 2 languages, not 14
            assert "2 languages" in captured.out.lower() or "2" in captured.out


